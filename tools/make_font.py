"""Render an ASCII font into a serialized C++ source file.

Reads a TTF, rasterizes each glyph into a fixed cell, and serializes a 1-bit
atlas blob into a generated .cpp with:

    std::span<const std::uint8_t> font_bytes()

The blob layout is:

    uint8 N          -- number of glyphs
    uint8 width      -- glyph width in px
    uint8 height     -- glyph height in px
    N x
        uint8 ch     -- character code
        bytes data   -- width*height bits, row-major, MSB-first (multiple of 8)
"""

import argparse
import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONT = (
    Path(__file__).resolve().parent.parent
    / "third-party"
    / "kode-mono"
    / "KodeMono-Regular.ttf"
)
CHARS = (
    r"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
    + "0123456789 .,;:!?()[]{}<>+-*/=~_@#$%^&|\"'"
)
WIDTH, HEIGHT = 14, 16  # cell size in px
SUPERSAMPLE = 1


def load_font(path: Path = FONT) -> ImageFont.FreeTypeFont:
    """Load a TTF font at the given path, or exit with an error."""
    return ImageFont.truetype(str(path), WIDTH * SUPERSAMPLE)


def render_glyph(font: ImageFont.FreeTypeFont, ch: str) -> bytes:
    """Return the width*height-bit packed glyph, or all-zeros if blank."""
    canvas = Image.new("L", (WIDTH * SUPERSAMPLE * 4, HEIGHT * SUPERSAMPLE * 3), 0)
    draw = ImageDraw.Draw(canvas)
    origin_x = WIDTH * SUPERSAMPLE  # glyph origin column
    baseline = HEIGHT * SUPERSAMPLE * 2  # canvas row; draw so baseline sits here
    draw.text((origin_x, baseline), ch, font=font, fill=255, anchor="ls")

    bbox = canvas.getbbox()
    if bbox is None:
        return bytes(WIDTH * HEIGHT // 8)

    # Horizontally center the ink within a WIDTH*S wide window.
    l, _, r, _ = bbox
    x0 = origin_x - (WIDTH * SUPERSAMPLE - (r - l)) // 2

    # Vertically align to a shared baseline: 1 final row = S superpixels.
    ascent, _ = font.getmetrics()
    rb = min(HEIGHT - 2, math.ceil(ascent / SUPERSAMPLE))  # baseline final row
    y0 = baseline - rb * SUPERSAMPLE

    cell = canvas.crop(
        (x0, y0, x0 + WIDTH * SUPERSAMPLE, y0 + HEIGHT * SUPERSAMPLE)
    ).resize((WIDTH, HEIGHT), Image.LANCZOS)
    bw = cell.point(lambda p: 255 if p >= 128 else 0).convert("1")

    out = bytearray((WIDTH * HEIGHT) // 8)
    for row in range(HEIGHT):
        for col in range(WIDTH):
            if bw.getpixel((col, row)):
                bit = row * WIDTH + col
                out[bit // 8] |= 1 << (7 - bit % 8)
    return bytes(out)


def main() -> None:
    assert (WIDTH * HEIGHT) % 8 == 0, "glyph bits must be a multiple of 8"

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-o", "--output", type=Path, required=True)
    args = parser.parse_args()

    blob = bytearray()
    blob.append(len(CHARS))
    blob.append(WIDTH)
    blob.append(HEIGHT)
    font = load_font()
    for ch in CHARS:
        blob.append(ord(ch))
        blob += render_glyph(font, ch)

    data = ", ".join(str(x) for x in blob)
    cpp = f"""#include "game.hpp"

// Generated by tools/make_font.py; do not edit.
namespace {{
constexpr std::uint8_t kFontData[{len(blob)}] = {{
{data}
}};
}}  // namespace

std::span<const std::uint8_t> font_bytes() {{
    return {{kFontData, sizeof(kFontData)}};
}}
"""
    path = args.output
    if path.exists() and path.read_text() == cpp:
        print(f"unchanged {path}")
    else:
        path.write_text(cpp)
        print(f"wrote {path}  ({len(CHARS)} glyphs, {len(blob)} bytes)")


if __name__ == "__main__":
    main()
